/**
 * Test fixtures: real Office files, not hand-written XML.
 *
 * `docx` and `pptxgenjs` produce complete packages — styles, themes, numbering,
 * relationships, the lot — so the tests run against the same shape of file a
 * person would actually drop on the page. Where a case can't be expressed
 * through those libraries (tracked changes, hidden runs, comment anchors), the
 * document part is swapped for hand-written XML inside an otherwise real
 * package, which keeps the rest of the archive honest.
 */

import {
  Document,
  ExternalHyperlink,
  Packer,
  Paragraph,
  Table,
  TableCell,
  TableRow,
  TextRun,
} from "docx";
import PptxGenJS from "pptxgenjs";
import { makeEntry, readEntry, readZip, writeZip, type ZipEntry } from "../src/ooxml/zip";

const encoder = new TextEncoder();
const decoder = new TextDecoder();

/** A Word document carrying one of everything: curly punctuation, an invisible
    tag character, an emoji, literal markdown, a citation marker, assistant
    asides in the body and in a table, a tracked link and a chat link. */
export async function makeDocx(): Promise<File> {
  const doc = new Document({
    creator: "ChatGPT",
    lastModifiedBy: "ChatGPT",
    description: "Generated by ChatGPT",
    keywords: "ai, draft",
    sections: [
      {
        children: [
          new Paragraph({ children: [new TextRun("Certainly! Here’s your report.")] }),
          new Paragraph({
            children: [
              new TextRun("The team’s “roadmap” — covering 2024–2025 — is ready… "),
              new TextRun(
                "Costs rose 3×5​% \u{E0041} \u{1F680} → **bold** • bullets 【4:0†source】",
              ),
            ],
          }),
          new Paragraph({
            children: [
              new TextRun("See "),
              new ExternalHyperlink({
                children: [new TextRun("the source")],
                link: "https://example.org/report?ref=x&utm_source=chatgpt.com&utm_medium=chat",
              }),
              new TextRun(" and "),
              new ExternalHyperlink({
                children: [new TextRun("this chat")],
                link: "https://chatgpt.com/share/abc123",
              }),
              new TextRun("."),
            ],
          }),
          new Paragraph({
            children: [
              new TextRun(
                "Delve into the tapestry; moreover, it’s important to note the seamless, robust approach.",
              ),
            ],
          }),
          new Table({
            rows: [
              new TableRow({
                children: [
                  new TableCell({ children: [new Paragraph("I hope this helps!")] }),
                  new TableCell({
                    children: [
                      new Paragraph("Let me know if you need more."),
                      new Paragraph("Real cell – content"),
                    ],
                  }),
                ],
              }),
            ],
          }),
          new Paragraph({ children: [new TextRun("Let me know if you need anything else!")] }),
        ],
      },
    ],
  });

  // `Buffer` and `BlobPart` disagree in the type system, not at runtime.
  return new File([new Uint8Array(await Packer.toBuffer(doc))], "report.docx");
}

/** A deck with the same character traces, an assistant aside as the only text
    in one shape, and PowerPoint's own per-shape creation GUIDs. */
export async function makePptx(): Promise<File> {
  const pptx = new PptxGenJS();
  pptx.author = "ChatGPT";
  pptx.company = "OpenAI";
  pptx.title = "Roadmap";

  const slide = pptx.addSlide();
  slide.addText("Roadmap — 2024–2025 \u{1F680}", { x: 0.5, y: 0.5, w: 9, h: 1, fontSize: 28 });
  slide.addText("Sure! Here’s your deck.", { x: 0.5, y: 1.6, w: 9, h: 0.8 });
  slide.addText("Delve into the tapestry — it’s a “game-changer”…", {
    x: 0.5,
    y: 2.4,
    w: 9,
    h: 0.8,
  });

  const second = pptx.addSlide();
  second.addText("I hope this helps!", { x: 0.5, y: 0.5, w: 9, h: 1 });

  const buffer = (await pptx.write({ outputType: "nodebuffer" })) as Buffer;
  return new File([new Uint8Array(buffer)], "roadmap.pptx");
}

