/** Swaps one part inside an otherwise real package. */
export async function withPart(file: File, name: string, xml: string): Promise<File> {
  const entries = readZip(await file.arrayBuffer());
  const replaced: ZipEntry[] = [];
  for (const entry of entries) {
    replaced.push(entry.name === name ? await makeEntry(name, encoder.encode(xml)) : entry);
  }
  return new File([writeZip(replaced)], file.name);
}

/** Every XML part of an archive, decoded, keyed by part name. */
export async function readParts(blob: Blob): Promise<Map<string, string>> {
  const parts = new Map<string, string>();
  for (const entry of readZip(await blob.arrayBuffer())) {
    if (/\.(xml|rels)$/.test(entry.name)) {
      parts.set(entry.name, decoder.decode(await readEntry(entry)));
    }
  }
  return parts;
}

export async function partNames(blob: Blob): Promise<string[]> {
  return readZip(await blob.arrayBuffer()).map((e) => e.name);
}
